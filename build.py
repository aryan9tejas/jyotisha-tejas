#!/usr/bin/env python3
"""Regenerates www/py/manifest.json and www/sw.js (precache list + version hash). Run after changing anything in www/."""
import hashlib, json, os
W = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'www')
py = sorted(os.path.relpath(os.path.join(d, f), os.path.join(W, 'py')).replace(os.sep, '/')
            for d, _, fs in os.walk(os.path.join(W, 'py')) for f in fs if f.endswith('.py') and '__pycache__' not in d)
json.dump(py, open(os.path.join(W, 'py', 'manifest.json'), 'w'))
files = sorted(os.path.relpath(os.path.join(d, f), W).replace(os.sep, '/') for d, _, fs in os.walk(W) for f in fs
               if f not in ('sw.js',) and not f.endswith(('.map', '.pyc')) and '__pycache__' not in d)
h = hashlib.sha256()
for f in files:
    h.update(f.encode()); h.update(open(os.path.join(W, f), 'rb').read())
ver = h.hexdigest()[:12]
sw = f"""/* Jyotisha Tejas service worker (generated by build.py): caches every file so the app works with no network. */
const CACHE = 'jt-{ver}';
const FILES = {json.dumps(['./'] + files)};
self.addEventListener('install', e => {{ e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); }});
self.addEventListener('activate', e => {{ e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); }});
self.addEventListener('fetch', e => {{
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, {{ignoreSearch: true}}).then(r => r || fetch(e.request)));
}});
"""
open(os.path.join(W, 'sw.js'), 'w').write(sw)
print('files', len(files), 'version', ver, 'bytes', sum(os.path.getsize(os.path.join(W, f)) for f in files))
